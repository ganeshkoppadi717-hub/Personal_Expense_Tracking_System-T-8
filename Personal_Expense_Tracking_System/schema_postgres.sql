-- PostgreSQL schema for Vercel-managed Neon. Safe to run more than once.

CREATE TABLE IF NOT EXISTS profiles (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name       VARCHAR(50) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE UNIQUE INDEX IF NOT EXISTS uq_profiles_name_ci
    ON profiles (LOWER(name));

CREATE TABLE IF NOT EXISTS categories (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        VARCHAR(50) NOT NULL,
    description VARCHAR(255),
    created_at  TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE UNIQUE INDEX IF NOT EXISTS uq_categories_name_ci
    ON categories (LOWER(name));

CREATE TABLE IF NOT EXISTS expenses (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title        VARCHAR(100) NOT NULL,
    amount       NUMERIC(10, 2) NOT NULL CHECK (amount > 0),
    expense_date DATE NOT NULL,
    category_id  BIGINT NOT NULL REFERENCES categories (id) ON DELETE RESTRICT,
    profile_id   BIGINT NOT NULL REFERENCES profiles (id) ON DELETE RESTRICT,
    notes        VARCHAR(500),
    created_at   TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_expenses_date ON expenses (expense_date);
CREATE INDEX IF NOT EXISTS idx_expenses_category ON expenses (category_id);
CREATE INDEX IF NOT EXISTS idx_expenses_profile ON expenses (profile_id);

INSERT INTO profiles (name)
SELECT 'Household'
WHERE NOT EXISTS (
    SELECT 1 FROM profiles WHERE LOWER(name) = LOWER('Household')
);
